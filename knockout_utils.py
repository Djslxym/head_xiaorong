#!/usr/bin/env python3
"""Utilities for single-query-head zero ablation inside HAWK's VLMEvalKit run.

The HAWK adapter imports ``configure_model`` from ``hawk.integration``.  We
install a temporary ``sitecustomize.py`` on PYTHONPATH so that each torchrun
worker wraps that function before ``hawk.vlmeval_adapter`` imports it.  The
wrapper installs a forward-pre-hook on the selected layer's self_attn.o_proj.
"""
from __future__ import annotations

import csv
import json
import os
import subprocess
import sys
import tempfile
from datetime import datetime
from pathlib import Path
from typing import Any


def parse_gpu_ids(value: str) -> list[str]:
    gpu_ids = [item.strip() for item in value.split(",") if item.strip()]
    if not gpu_ids:
        raise ValueError("--gpus must contain at least one GPU id, e.g. 0 or 0,1")
    if len(set(gpu_ids)) != len(gpu_ids):
        raise ValueError(f"duplicate GPU ids in --gpus: {value}")
    return gpu_ids


def make_run_prefix(task: str, layer: int, head: int, requested: str | None) -> str:
    if requested:
        return requested
    stamp = datetime.now().strftime("%Y%m%d_%H%M%S")
    return f"{task}_L{layer:02d}_H{head:02d}_{stamp}"


def write_sitecustomize(directory: Path) -> Path:
    """Create the temporary import-time patch used only by the ablation run."""
    directory.mkdir(parents=True, exist_ok=True)
    sitecustomize = directory / "sitecustomize.py"
    source = r'''# Auto-generated by 3_knockouts.py; do not install permanently.
import os

if os.environ.get("HAWK_HEAD_ABLATION_ENABLE") == "1":
    import hawk.integration as _hawk_integration

    if not getattr(_hawk_integration, "_head_ablation_wrapped", False):
        _original_configure_model = _hawk_integration.configure_model

        def _configure_model_with_head_ablation(model, config=None):
            result = _original_configure_model(model, config)

            layer_index = int(os.environ["HAWK_ABLATION_LAYER"])
            head_index = int(os.environ["HAWK_ABLATION_HEAD"])

            inner = getattr(model, "model", None)
            language_model = getattr(inner, "language_model", None)
            layers = getattr(language_model, "layers", None)
            if layers is None:
                raise RuntimeError(
                    "Cannot locate Qwen2.5-VL layers at model.model.language_model.layers"
                )
            if not 0 <= layer_index < len(layers):
                raise IndexError(
                    f"layer={layer_index} is out of range [0, {len(layers) - 1}]"
                )

            layer = layers[layer_index]
            attention = getattr(layer, "self_attn", None)
            if attention is None or not hasattr(attention, "o_proj"):
                raise RuntimeError(f"Layer {layer_index} has no self_attn.o_proj")

            num_heads = int(getattr(attention, "num_heads", 0))
            head_dim = getattr(attention, "head_dim", None)
            if head_dim is None:
                text_config = getattr(getattr(model, "config", None), "text_config", None)
                hidden_size = getattr(text_config, "hidden_size", None)
                if hidden_size is None or not num_heads:
                    raise RuntimeError("Cannot infer Qwen2.5-VL attention head dimension")
                head_dim = int(hidden_size) // num_heads
            head_dim = int(head_dim)

            if num_heads <= 0:
                raise RuntimeError("Invalid attention.num_heads in the loaded model")
            if not 0 <= head_index < num_heads:
                raise IndexError(
                    f"head={head_index} is out of range [0, {num_heads - 1}]"
                )

            start = head_index * head_dim
            end = start + head_dim
            projection_width = getattr(attention.o_proj, "in_features", None)
            if projection_width is not None and int(projection_width) != num_heads * head_dim:
                raise RuntimeError(
                    "o_proj input width does not equal num_heads * head_dim: "
                    f"{projection_width} != {num_heads} * {head_dim}"
                )

            def _zero_selected_query_head(module, inputs):
                if not inputs:
                    return None
                hidden = inputs[0]
                if not hasattr(hidden, "shape") or hidden.shape[-1] != num_heads * head_dim:
                    raise RuntimeError(
                        "Unexpected o_proj input shape; expected last dimension "
                        f"{num_heads * head_dim}, got "
                        f"{getattr(hidden, 'shape', None)}"
                    )
                modified = hidden.clone()
                modified[..., start:end] = 0
                return (modified,) + tuple(inputs[1:])

            hook_handle = attention.o_proj.register_forward_pre_hook(
                _zero_selected_query_head
            )
            # Keep the handle alive for the full lifetime of the model.
            model._hawk_head_ablation_hook = hook_handle
            model._hawk_head_ablation_spec = {
                "layer": layer_index,
                "head": head_index,
                "head_dim": head_dim,
                "start": start,
                "end": end,
                "num_heads": num_heads,
            }
            print(
                "[HAWK head ablation] zeroed Query Head "
                f"L{layer_index} H{head_index} (dims {start}:{end})",
                flush=True,
            )
            return result

        _hawk_integration.configure_model = _configure_model_with_head_ablation
        _hawk_integration._head_ablation_wrapped = True
'''
    sitecustomize.write_text(source, encoding="utf-8")
    return sitecustomize


def run_hawk_evaluation(
    project_root: Path,
    *,
    task: str,
    model_path: Path,
    gpu_ids: list[str],
    run_name: str,
    limit: int | None = None,
    num_processes: int | None = None,
    skip_data_download: bool = False,
    dry_run: bool = False,
    ablation: tuple[int, int] | None = None,
    patch_dir: Path | None = None,
) -> None:
    """Call HAWK's own evaluator with pruning disabled and optional head hook."""
    command = [
        sys.executable,
        str(project_root / "scripts" / "evaluate.py"),
        "--task", task,
        "--pruning_ratio", "0.0",
        "--model_path", str(model_path),
        "--gpus", ",".join(gpu_ids),
        "--run_name", run_name,
    ]
    if num_processes is not None:
        command += ["--num_processes", str(num_processes)]
    if limit is not None:
        command += ["--limit", str(limit)]
    if skip_data_download:
        command.append("--skip_data_download")
    if dry_run:
        command.append("--dry_run")

    env = os.environ.copy()
    # evaluate_vlmeval.sh prepends HAWK's src/runtime paths but preserves this
    # PYTHONPATH suffix; sitecustomize is consequently loaded by torchrun too.
    if ablation is not None:
        if patch_dir is None:
            raise ValueError("patch_dir is required for an ablation run")
        env["PYTHONPATH"] = os.pathsep.join(
            [str(patch_dir), str(project_root / "src"), env.get("PYTHONPATH", "")]
        ).rstrip(os.pathsep)
        env["HAWK_HEAD_ABLATION_ENABLE"] = "1"
        env["HAWK_ABLATION_LAYER"] = str(ablation[0])
        env["HAWK_ABLATION_HEAD"] = str(ablation[1])
    else:
        env.pop("HAWK_HEAD_ABLATION_ENABLE", None)
        env.pop("HAWK_ABLATION_LAYER", None)
        env.pop("HAWK_ABLATION_HEAD", None)

    print("\n[HAWK evaluation command]", flush=True)
    print(" ".join(command), flush=True)
    subprocess.run(command, cwd=project_root, env=env, check=True)


def discover_score_files(result_dir: Path) -> list[str]:
    """Return native VLMEvalKit accuracy/score artifact paths without guessing values."""
    if not result_dir.exists():
        return []
    matches: list[str] = []
    for path in result_dir.rglob("*"):
        if path.is_file() and any(token in path.name.lower() for token in ("acc", "score")):
            matches.append(str(path.resolve()))
    return sorted(matches)


def extract_realworldqa_accuracy(result_dir: Path) -> float | None:
    """Read the Overall value from HAWK/VLMEvalKit's native RealWorldQA *_acc.csv.

    ImageMCQDataset.report_acc returns an ``Overall`` column as a fraction in
    [0, 1], with a ``split`` column (normally ``none`` for RealWorldQA).
    Return a percentage in [0, 100].  If the expected native artifact is not
    present or has an unfamiliar schema, return None rather than guessing.
    """
    candidates = [
        path for path in result_dir.rglob("*.csv")
        if "acc" in path.name.lower()
    ] if result_dir.exists() else []
    for path in sorted(candidates):
        try:
            with path.open("r", encoding="utf-8-sig", newline="") as stream:
                rows = list(csv.DictReader(stream))
            if not rows:
                continue
            normalized = {
                str(key).strip().lower(): key
                for key in rows[0].keys()
                if key is not None
            }
            overall_key = normalized.get("overall")
            if overall_key is None:
                continue
            split_key = normalized.get("split")
            selected = None
            if split_key is not None:
                for row in rows:
                    split_value = str(row.get(split_key, "")).strip().lower()
                    if split_value in {"none", "overall", "nan", ""}:
                        selected = row
                        break
            if selected is None:
                selected = rows[0]
            value = float(selected[overall_key])
            if not (value >= 0.0):
                continue
            return value * 100.0 if value <= 1.0 else value
        except (OSError, ValueError, TypeError, KeyError):
            continue
    return None


def write_experiment_manifest(
    path: Path,
    *,
    task: str,
    layer: int,
    head: int,
    model_path: Path,
    baseline_dir: Path,
    ablated_dir: Path,
    limit: int | None,
) -> None:
    payload: dict[str, Any] = {
        "task": task,
        "model_path": str(model_path),
        "pruning_ratio": 0.0,
        "keep_ratio": 1.0,
        "ablation": {"type": "zero_query_head_output", "layer": layer, "head": head},
        "limit": limit,
        "baseline_result_dir": str(baseline_dir),
        "baseline_native_score_files": discover_score_files(baseline_dir),
        "baseline_accuracy_percent": extract_realworldqa_accuracy(baseline_dir),
        "ablated_result_dir": str(ablated_dir),
        "ablated_native_score_files": discover_score_files(ablated_dir),
        "ablated_accuracy_percent": extract_realworldqa_accuracy(ablated_dir),
        "accuracy_drop_percentage_points": None,
        "note": (
            "Accuracy values are read from the native RealWorldQA *_acc.csv "
            "produced by VLMEvalKit (Overall). No text-difference proxy is used."
        ),
    }
    baseline_accuracy = payload["baseline_accuracy_percent"]
    ablated_accuracy = payload["ablated_accuracy_percent"]
    if baseline_accuracy is not None and ablated_accuracy is not None:
        payload["accuracy_drop_percentage_points"] = round(
            baseline_accuracy - ablated_accuracy, 6
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
